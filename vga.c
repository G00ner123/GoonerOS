void put_pixel(int x, int y, unsigned int color) {
    if((unsigned)x >= VESA_WIDTH || (unsigned)y >= VESA_HEIGHT) return;
    unsigned char* p = (unsigned char*)framebuffer + y * fb_pitch + x * (fb_bpp / 8);
    p[0] = color & 0xFF;
    p[1] = (color >> 8) & 0xFF;
    p[2] = (color >> 16) & 0xFF;
    if(fb_bpp == 32) p[3] = 0;
}
unsigned int get_pixel(int x, int y) {
    if((unsigned)x >= VESA_WIDTH || (unsigned)y >= VESA_HEIGHT) return 0;
    unsigned char* p = (unsigned char*)framebuffer + y * fb_pitch + x * (fb_bpp / 8);
    return (p[2] << 16) | (p[1] << 8) | p[0];
}
void draw_char(int x, int y, char c, unsigned int fg, unsigned int bg) {
    const unsigned char* glyph = font8x16[(unsigned char)c];
    int i, j;
    for(j = 0; j < 16; j++) {
        unsigned char row = glyph[j];
        for(i = 0; i < 8; i++) {
            put_pixel(x+i, y+j, (row & (0x80 >> i))? fg : bg);
        }
    }
}
static char text_buffer[TEXT_ROWS][TEXT_COLS];
void text_buffer_put(int row, int col, char c) {
    if(row >= 0 && row < TEXT_ROWS && col >= 0 && col < TEXT_COLS) text_buffer[row][col] = c;
}
static void vga_scroll(void) {
    int i, j;
    for(j = term_oy; j < term_oy+term_h-16; j++)
        for(i = term_ox; i < term_ox+term_w; i++)
            put_pixel(i, j, get_pixel(i, j+16));
    for(j = term_oy+term_h-16; j < term_oy+term_h; j++)
        for(i = term_ox; i < term_ox+term_w; i++)
            put_pixel(i, j, 0x000);
    text_y -= 16;
    for(int r = 0; r < TEXT_ROWS-1; r++)
        for(int c = 0; c < TEXT_COLS; c++)
            text_buffer[r][c] = text_buffer[r+1][c];
    for(int c = 0; c < TEXT_COLS; c++) text_buffer[TEXT_ROWS-1][c] = 0;
}
void clear_pixels_only(void) {
    for(int j = 0; j < VESA_HEIGHT; j++)
        for(int i = 0; i < VESA_WIDTH; i++)
            put_pixel(i, j, 0x000);
}
void vga_clear(void) {
    int i, j;
    for(j = 0; j < VESA_HEIGHT; j++)
        for(i = 0; i < VESA_WIDTH; i++)
            put_pixel(i, j, 0x000);
    text_x = term_ox; text_y = term_oy;
    for(int r = 0; r < TEXT_ROWS; r++)
        for(int c = 0; c < TEXT_COLS; c++)
            text_buffer[r][c] = 0;
}
// Wie vga_clear(), leert aber NUR den aktuellen Fensterbereich statt des
// gesamten Bildschirms - fuer ein Terminal-Fenster auf dem Desktop, damit
// Hintergrund/Icons/Taskleiste dabei nicht mitgeloescht werden.

void vga_clear_region(void) {
    for(int j = term_oy; j < term_oy+term_h; j++)
        for(int i = term_ox; i < term_ox+term_w; i++)
            put_pixel(i, j, 0x000);
    text_x = term_ox; text_y = term_oy;
    for(int r = 0; r < TEXT_ROWS; r++)
        for(int c = 0; c < TEXT_COLS; c++)
            text_buffer[r][c] = 0;
}
void vga_putc(char c) {
    if(c == '\n') { text_x = term_ox; text_y += 16; }
    else if(c == '\b') {
        if(text_x > term_ox) {
            text_x -= 8;
            draw_char(text_x, text_y, ' ', 0xFFFFFF, 0);
            text_buffer_put((text_y-term_oy)/16, (text_x-term_ox)/8, 0);
        }
    } else {
        draw_char(text_x, text_y, c, text_color, 0x000);
        text_buffer_put((text_y-term_oy)/16, (text_x-term_ox)/8, c);
        text_x += 8;
    }
    if(text_x >= term_ox+term_w) { text_x = term_ox; text_y += 16; }
    if(text_y >= term_oy+term_h) vga_scroll();
}
void redraw_text_buffer(void) {
    int cols = term_w / 8;
    int rows = term_h / 16;
    if(cols > TEXT_COLS) cols = TEXT_COLS;
    if(rows > TEXT_ROWS) rows = TEXT_ROWS;
    for(int r = 0; r < rows; r++)
        for(int c = 0; c < cols; c++)
            if(text_buffer[r][c]) draw_char(term_ox+c*8, term_oy+r*16, text_buffer[r][c], 0xFFFFFF, 0x000000);
}
void vga_print(const char* s) { while(*s) vga_putc(*s++); }
void draw_rect(int x, int y, int w, int h, unsigned int color) {
    if(w <= 0 || h <= 0) return;
    if(x < 0) { w += x; x = 0; }
    if(y < 0) { h += y; y = 0; }
    if(x + w > VESA_WIDTH) w = VESA_WIDTH - x;
    if(y + h > VESA_HEIGHT) h = VESA_HEIGHT - y;
    if(w <= 0 || h <= 0) return;
    for(int j = 0; j < h; j++)
        for(int i = 0; i < w; i++)
            put_pixel(x + i, y + j, color);
}
void draw_char_scaled(int x, int y, char c, int scale, unsigned int fg, unsigned int bg) {
    const unsigned char* glyph = font8x16[(unsigned char)c];
    for(int j = 0; j < 16; j++) {
        unsigned char row = glyph[j];
        for(int i = 0; i < 8; i++) {
            draw_rect(x + i*scale, y + j*scale, scale, scale, (row & (0x80 >> i)) ? fg : bg);
        }
    }
}
static int edge_cross(int ax,int ay,int bx,int by,int px,int py) {
    return (bx-ax)*(py-ay) - (by-ay)*(px-ax);
}
void draw_triangle(int x0,int y0,int x1,int y1,int x2,int y2, unsigned int color) {
    int minx = x0, maxx = x0, miny = y0, maxy = y0;
    if(x1<minx) minx=x1; if(x1>maxx) maxx=x1;
    if(x2<minx) minx=x2; if(x2>maxx) maxx=x2;
    if(y1<miny) miny=y1; if(y1>maxy) maxy=y1;
    if(y2<miny) miny=y2; if(y2>maxy) maxy=y2;
    for(int y = miny; y <= maxy; y++) {
        for(int x = minx; x <= maxx; x++) {
            int w0 = edge_cross(x1,y1,x2,y2,x,y);
            int w1 = edge_cross(x2,y2,x0,y0,x,y);
            int w2 = edge_cross(x0,y0,x1,y1,x,y);
            if((w0>=0 && w1>=0 && w2>=0) || (w0<=0 && w1<=0 && w2<=0))
                put_pixel(x,y,color);
        }
    }
}
void draw_mouse(int x, int y, unsigned int color) {
    draw_triangle(x, y, x, y+11, x+6, y+8, color);
}
void draw_circle_filled(int cx, int cy, int r, unsigned int color) {
    for(int y = -r; y <= r; y++) {
        for(int x = -r; x <= r; x++) {
            if(x*x + y*y <= r*r) put_pixel(cx+x, cy+y, color);
        }
    }
}
void draw_arch_logo(int cx, int top_y, int height, int half_width, unsigned int color) {
    int base_y = top_y + height;
    unsigned int dark  = 0x0E6FA3;   // dunkleres Blau, linkes "Bein"
    unsigned int light = 0x2BB3E8;   // helleres Blau, rechtes "Bein"

    // Linke und rechte Haelfte getrennt einfaerben (Zweiton-Verlauf wie beim Original)
    draw_triangle(cx, top_y, cx-half_width, base_y, cx, base_y, dark);
    draw_triangle(cx, top_y, cx, base_y, cx+half_width, base_y, light);

    // Torbogen-Aussparung von unten (Halbkreis oben + gerader Schacht) - schmaler, damit die Beine dicker bleiben
    int arch_r = half_width * 3 / 10;
    int arch_top = top_y + height * 45 / 100;
    for(int y = -arch_r; y <= 0; y++)
        for(int x = -arch_r; x <= arch_r; x++)
            if(x*x + y*y <= arch_r*arch_r) put_pixel(cx+x, arch_top+arch_r+y, 0x000000);
    draw_rect(cx - arch_r, arch_top + arch_r, arch_r*2, base_y - (arch_top+arch_r) + 1, 0x000000);

    // Kleine Kerbe am linken Rand, angelehnt ans Original (bewusst vereinfacht/asymmetrisch)
    int lx = cx - half_width * 32 / 100;
    int ly = top_y + height * 32 / 100;
    draw_triangle(lx, ly,
                  lx - half_width*14/100, ly + height*7/100,
                  lx + half_width*10/100, ly + height*13/100,
                  0x000000);
}
void draw_mint_logo(int show) {
    // Eigene Interpretation aus Grundformen (Kreis + L/M-Monogramm), kein Vektor-Trace des Originals
    int cx = 865, cy = 480, r = 80;

    if(!show) {
        draw_rect(cx-r-6, cy-r-6, 2*(r+6), 2*(r+6), 0x000000);
        return;
    }

    unsigned int green = 0x64B445;
    unsigned int white = 0xF5F5F5;

    draw_circle_filled(cx, cy, r, green);

    // "L"-Balken links, oben abgerundet
    int lx = cx - 44, lw = 20;
    int top_y = cy - 42;
    draw_rect(lx, top_y, lw, 68, white);
    draw_circle_filled(lx+lw/2, top_y, lw/2, white);

    // Breiter, abgerundeter Steg unten -> verbindet L und M zu einer gemeinsamen Kontur
    int base_y = cy + 18, base_h = 26, base_right = cx + 46;
    draw_rect(lx, base_y, base_right-lx, base_h, white);
    draw_circle_filled(lx+lw/2, base_y+base_h/2, base_h/2, white);
    draw_circle_filled(base_right, base_y+base_h/2, base_h/2, white);

    // "M": zwei Boegen, oben abgerundet, sitzen auf dem Steg
    int m_top = cy - 12, m_h = 45, leg_w = 16;
    int m1x = cx - 6, m2x = cx + 25;
    draw_rect(m1x, m_top, leg_w, m_h, white);
    draw_rect(m2x, m_top, leg_w, m_h, white);
    draw_circle_filled(m1x+leg_w/2, m_top, leg_w/2, white);
    draw_circle_filled(m2x+leg_w/2, m_top, leg_w/2, white);

    // Aeussere rechte Kontur des M, damit beide Boegen wie aus einem Stueck wirken
    int outer_x = m2x + leg_w + 4;
    draw_rect(outer_x, m_top, leg_w, m_h, white);
    draw_circle_filled(outer_x+leg_w/2, m_top, leg_w/2, white);

    // Gruen zwischen den Boegen wieder freilegen (die zwei "Fenster" des M),
    // erst unterhalb der abgerundeten Kappen, damit die Rundungen sauber bleiben
    int window_top = m_top + leg_w/2;
    draw_rect(m1x+leg_w, window_top, m2x-(m1x+leg_w), 20, green);
    draw_rect(m2x+leg_w, window_top, outer_x-(m2x+leg_w), 20, green);
}

void play_gooneros_animation(void) {
    const char* msg = "GoonerOS";
    unsigned int colors[] = {0xFF5555, 0xFFAA00, 0xFFFF55, 0x55FF55, 0x55AAFF, 0xAA55FF};
    int scale = 4;
    int char_w = 8*scale;
    int len = 0; while(msg[len]) len++;
    int gx = (VESA_WIDTH - len*char_w) / 2;
    int gy = (VESA_HEIGHT - 16*scale) / 2;
    draw_rect(gx-20, gy-20, len*char_w+40, 16*scale+40, 0x000000);
    for(int i = 0; msg[i]; i++) {
        draw_char_scaled(gx + i*char_w, gy, msg[i], scale, colors[i % 6], 0x000000);
        pit_wait_ms(150);
    }
    pit_wait_ms(2000);
    draw_rect(gx-20, gy-20, len*char_w+40, 16*scale+40, 0x000000);
    if(mint_visible) draw_mint_logo(1);
}

// 16x16 Pixel-Herz, Bit=1 heisst "gefuellt" - genau wie die font8x16-Tabelle
// oben, nur als eigene kleine Bitmap statt Buchstabe.
static const unsigned short heart_bitmap[16] = {
    0x0E70,0x3FFC,0x7FFE,0xFFFF,0xFFFF,0xFFFF,0xFFFF,0x7FFE,
    0x7FFE,0x3FFC,0x3FFC,0x1FF8,0x1FF8,0x07E0,0x03C0,0x0180
};
void draw_heart(int cx, int cy, int scale, unsigned int color) {
    if(scale < 1) return;
    int w = 16*scale, h = 16*scale;
    int x0 = cx - w/2, y0 = cy - h/2;
    for(int row = 0; row < 16; row++) {
        unsigned short bits = heart_bitmap[row];
        for(int col = 0; col < 16; col++)
            if(bits & (0x8000 >> col))
                draw_rect(x0 + col*scale, y0 + row*scale, scale, scale, color);
    }
    if(color != 0x000000 && scale >= 3) {
        // Kleines Glanzlicht oben links fuer einen leicht glossy Look
        draw_circle_filled(x0 + 4*scale, y0 + 4*scale, scale, 0xFF6E86);
    }
}

// ==================== Desktop-Vorkehrungen ====================
// UI-Akzentfarbe, ueber den "theme"-Befehl aenderbar - wird schon jetzt
// fuer den Eingabe-Cursor benutzt, spaeter auch fuer Fenster-Titelleisten.
unsigned int ui_theme_color = 0x00FFAA;

// Grundbaustein fuer den kommenden Fenster-Desktop: Koerper + Titelleiste
// + duenner Rahmen, alles aus bereits vorhandenen draw_rect/draw_char
// zusammengesetzt (genau wie draw_arch_logo/draw_mint_logo das schon tun).
void draw_window(int x, int y, int w, int h, const char* title) {
    draw_rect(x, y, w, h, 0x1A1A1A);

    // Leichter Verlauf in der Titelleiste (100% -> 75% Helligkeit von oben
    // nach unten) statt einer platten Farbflaeche - wirkt weniger nach
    // Windows-95-Flatstyle, kostet aber praktisch nichts extra.
    unsigned char r = (ui_theme_color>>16)&0xFF, g=(ui_theme_color>>8)&0xFF, b=ui_theme_color&0xFF;
    for(int i = 0; i < 20; i++) {
        int pct = 100 - (i*25)/20;
        unsigned int rr = (r*pct)/100, gg = (g*pct)/100, bb = (b*pct)/100;
        draw_rect(x, y+i, w, 1, (rr<<16)|(gg<<8)|bb);
    }
    for(int i = 0; title[i] && i*8 < w-16; i++)
        draw_char(x+6+i*8, y+2, title[i], 0x000000, ui_theme_color);
    draw_rect(x, y, w, 2, 0xFFFFFF);
    draw_rect(x, y, 2, h, 0xFFFFFF);
    draw_rect(x+w-2, y, 2, h, 0xFFFFFF);
    draw_rect(x, y+h-2, w, 2, 0xFFFFFF);
}
