// Terminal-Fensterbereich: wo und wie gross das Terminal gerade zeichnet.
// Default = ganzer Bildschirm, exakt wie bisher. Der Desktop kann das per
// vga_set_region() auf einen kleineren Bereich (mit Platz fuer Titelleiste
// und Rand) umstellen, ohne dass sich am Text-Rendering selbst was aendert.
static int term_ox = 0, term_oy = 0;
static int term_w = TEXT_WRAP_WIDTH;
static int term_h = VESA_HEIGHT;

void vga_set_region(int ox, int oy, int w, int h) {
    // Sicherheitsbegrenzung: text_buffer ist fest TEXT_ROWS x TEXT_COLS
    // gross, darueber hinaus darf der Bereich nie wachsen.
    if(ox < 0) ox = 0;
    if(oy < 0) oy = 0;
    if(ox >= VESA_WIDTH) ox = VESA_WIDTH - 1;
    if(oy >= VESA_HEIGHT) oy = VESA_HEIGHT - 1;
    if(w < 1) w = 1;
    if(h < 1) h = 1;
    if(w > TEXT_WRAP_WIDTH) w = TEXT_WRAP_WIDTH;
    if(h > VESA_HEIGHT) h = VESA_HEIGHT;
    if(ox + w > VESA_WIDTH) w = VESA_WIDTH - ox;
    if(oy + h > VESA_HEIGHT) h = VESA_HEIGHT - oy;
    term_ox = ox; term_oy = oy; term_w = w; term_h = h;
}
void vga_get_region(int* ox, int* oy, int* w, int* h) {
    *ox = term_ox; *oy = term_oy; *w = term_w; *h = term_h;
}
void vga_set_text_color(unsigned int color) {
    text_color = color & 0xFFFFFF;
}
int mint_visible = 0;

void vga_init(unsigned int fb_addr, unsigned int pitch, unsigned int bpp) {
    framebuffer = (volatile unsigned char*)fb_addr;
    fb_pitch = pitch;
    fb_bpp = bpp;
}

unsigned int vga_get_pitch(void) { return fb_pitch; }
unsigned int vga_get_bpp(void) { return fb_bpp; }

